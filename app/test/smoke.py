def handle(route):
    u = route.request.url
    if u.startswith("file://"): return route.continue_()
    if "unpkg.com/leaflet" in u:
        if u.endswith(".js"): return route.fulfill(status=200, content_type="application/javascript", body=STUB)
        return route.fulfill(status=200, content_type="text/css", body="")
    if "overpass-api.de" in u:   # accessibilité : 1 place PMR à 40 m, escalier (pas de rampe) à 30 m, toilettes accessibles à 200 m
        els = [{"type": "node", "lat": 48.5002, "lon": -4.6, "tags": {"amenity": "parking", "capacity:disabled": "2"}},
               {"type": "way", "center": {"lat": 48.5002, "lon": -4.6002}, "tags": {"highway": "steps"}},
               {"type": "node", "lat": 48.5015, "lon": -4.6, "tags": {"amenity": "toilets", "wheelchair": "yes"}}]
        return route.fulfill(status=200, content_type="application/json", body=json.dumps({"elements": els}))
    if "open-meteo.com" in u and "start_date=" in u:   # conditions d'un jour passé : houle 1,2 m puis 2,0 m, vent qui se lève l'après-midi
        d = u.split("start_date=")[1].split("&")[0]
        t = [f"{d}T{h:02d}:00" for h in range(24)]
        if "marine" in u: body = {"hourly": {"time": t, "wave_height": [1.2 if h < 15 else 2.0 for h in range(24)], "wave_period": [11.0] * 24, "wave_direction": [285] * 24, "sea_level_height_msl": [0.5 * (h % 6) - 1 for h in range(24)]}}
        else: body = {"hourly": {"time": t, "wind_speed_10m": [8.0 if h < 15 else 30.0 for h in range(24)], "wind_direction_10m": [90] * 24}}
        return route.fulfill(status=200, content_type="application/json", body=json.dumps(body))
    if "open-meteo.com" in u: calls['om'] += 1
    if "open-meteo.com" in u and "pressure_msl" in u and "unixtime" in u:   # pression : 20 hPa sous la normale (surcote ≈ +20 cm)
        import time
        t0 = int(time.time() // 3600 * 3600)
        return route.fulfill(status=200, content_type="application/json", body=json.dumps({"hourly": {"time": [t0 + i * 3600 for i in range(8 * 24)], "pressure_msl": [993.25] * (8 * 24)}}))
    if "marine" in u and "sea_level_height_msl" in u and "unixtime" in u and "wave_height" not in u:   # onglet Marées : onde de 12,42 h
        import math, time
        t0 = int(time.time() // 3600 * 3600)
        t = [t0 + i * 3600 for i in range(8 * 24)]
        body = {"utc_offset_seconds": 3600, "hourly": {"time": t, "sea_level_height_msl": [2.2 * math.cos((x - t0) * 2 * math.pi / (12.42 * 3600)) for x in t]}}
        return route.fulfill(status=200, content_type="application/json", body=json.dumps(body))
    if "open-meteo.com" in u and "unixtime" not in u:   # prévision d'un spot : houle 1,4 m à 11 s, vent faible, tous les jours
        t = [f"{(date.today() + timedelta(d)).isoformat()}T{h:02d}:00" for d in range(8) for h in range(24)]
        if "marine" in u: body = {"hourly": {"time": t, "wave_height": [1.4] * len(t), "wave_period": [11.0] * len(t), "wave_direction": [285] * len(t)}}
        else: body = {"hourly": {"time": t, "wind_speed_10m": [10.0] * len(t), "wind_direction_10m": [90] * len(t)}}
        return route.fulfill(status=200, content_type="application/json", body=json.dumps(body))
    return route.fulfill(status=404, body="")   # tout le reste : réseau coupé

